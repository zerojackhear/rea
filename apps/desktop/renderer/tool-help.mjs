export function toolHelp(tool) {
  const row = Object.hasOwn(toolGuides, tool.name)
    ? toolGuides[tool.name]
    : null;
  if (!row)
    return {
      title: tool.name,
      purpose: "此工具尚未补充中文说明。",
      how: "展开原始工具说明，核对用途与参数后操作。",
      note: "工具能力和限制以当前引擎返回的说明为准。",
      translated: false,
    };
  const [title, purpose, how, note] = row;
  return { title, purpose, how, note, translated: true };
}

export function toolSearchText(tool) {
  const help = toolHelp(tool);
  return [tool.name, tool.description ?? "", help.title, help.purpose, help.how]
    .join(" ")
    .toLowerCase();
}
